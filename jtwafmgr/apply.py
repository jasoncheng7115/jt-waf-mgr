MAX_REQUEST = 4 * 1024 * 1024


class Fail(Exception):
    def __init__(self, step, summary, **extra):
        super().__init__(summary)
        self.step, self.summary, self.extra = step, summary, extra


def sha256(b):
    return hashlib.sha256(b if isinstance(b, bytes) else b.encode('utf-8')).hexdigest()


def clean(s, n=4000):
    s = s.decode('utf-8', 'replace') if isinstance(s, bytes) else s
    return re.sub(r'[^\x09\x0a\x20-\x7e]', '?', s)[-n:]


def run(cmd, timeout=60):
    p = subprocess.run(cmd, capture_output=True, timeout=timeout)
    return p.returncode, clean(p.stdout + p.stderr)


class Applier:
    def __init__(self, cfg):
        self.cfg = cfg
        self.dir = cfg['managed']['dir']
        self.spool = cfg['managed']['spool']
        self.nginx = cfg['paths']['nginx_bin']
        self.state = cfg['managed']['apply_state']
        self.backups = os.path.join(self.state, 'snapshots')
        self._spool_fd = None

    # --- request validation ----------------------------------------------------------------
    def load_request(self, path):
        # the spool belongs to the service user: open without following links and check what was opened
        name = os.path.basename(path)
        dfd = self._spool_fd
        try:
            fd = os.open(name if dfd is not None else path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
                         dir_fd=dfd)
        except OSError as e:
            raise Fail('request', 'cannot open the request: %s' % e.strerror)
        with os.fdopen(fd, 'rb') as fh:
            st = os.fstat(fh.fileno())
            if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_REQUEST or st.st_nlink != 1:
                raise Fail('request', 'not a regular file or too large')
            req = json.loads(fh.read(MAX_REQUEST + 1).decode('utf-8'))
        if isinstance(req, dict) and req.get('action') == 'crs_switch':
            return self.check_crs(req)
        if isinstance(req, dict) and req.get('action') == 'blocks':
            return self.check_blocks(req)
        if not isinstance(req, dict) or req.get('action') != 'apply':
            raise Fail('request', 'unknown action')
        if not isinstance(req.get('version'), int) or not isinstance(req.get('change_id'), int):
            raise Fail('request', 'bad version or change id')
        files = req.get('files')
        if not isinstance(files, dict) or set(files) != set(FILES):
            raise Fail('request', 'files must be exactly: %s' % ', '.join(FILES))
        for p, text in files.items():
            if not isinstance(text, str) or sha256(text) != (req.get('sha256') or {}).get(p):
                raise Fail('request', 'checksum mismatch for %s' % p)
            if not text.startswith('# Generated by jt-waf-mgr'):
                raise Fail('request', '%s: missing jt-waf-mgr header' % p)
            body = text.split('\n\n', 1)[1] if '\n\n' in text else ''
            if len(text) > 4 * 1024 * 1024:
                raise Fail('request', '%s: file too large' % p)
            if body.strip():
                # the same per-rule checks as the workflow, done again here as root (never trust the request);
                # the limits are per rule, so the file is checked rule by rule
                from .managed import split_items
                ids = []
                for it in split_items(body):
                    if not it['text']:
                        continue
                    try:
                        ids += check_raw_text(it['text'], cfg=self.cfg)
                    except SpecError as e:
                        raise Fail('validate', '%s: rule %s: %s %s' % (p, it.get('rule_id'), e.code, e.details))
                lo, hi = self.cfg['waf']['local_range']
                bad = [i for i in ids if not lo <= i <= hi]
                if bad:
                    raise Fail('validate', '%s: rule ids outside the local range: %s' % (p, bad[:5]))
        urls = req.get('health_urls') or []
        if not isinstance(urls, list) or len(urls) > 100 or not all(
                isinstance(u, str) and re.fullmatch(r'https?://[a-z0-9.-]+(?::\d{1,5})?/\S{0,500}', u) for u in urls):
            raise Fail('request', 'bad health check list')
        adopt = req.get('adopt')
        if adopt is not None:
            self.check_adopt(adopt)
        return req

    def main_files(self):
        from .modsecconf import ModsecConfig
        from .nginxconf import NginxConfig
        n = NginxConfig(self.cfg['paths']['nginx_conf'])
        return ModsecConfig(n, self.cfg).main_files

    def check_adopt(self, adopt):
        main = adopt.get('main_conf')
        if main not in self.main_files():
            raise Fail('request', 'adopt: %r is not the main ModSecurity file' % main)
        rep = adopt.get('replace') or {}
        ins = adopt.get('insert') or {}
        if not isinstance(rep, dict) or not isinstance(ins, dict) or not (rep or ins):
            raise Fail('request', 'adopt: nothing to replace or insert')
        allowed = {os.path.join(self.dir, f) for f in FILES.values()}
        with open(main, encoding='utf-8') as fh:
            text = fh.read()
        includes = self.includes(main, text)
        for old, new in rep.items():
            if new not in allowed:
                raise Fail('request', 'adopt: %r is not a managed file' % new)
            if old not in includes:
                raise Fail('request', 'adopt: %r is not included by %s' % (old, main))
        # a fresh ModSecurity without site rule files: the managed file goes right next to a CRS rules Include
        for new, how in ins.items():
            if new not in allowed:
                raise Fail('request', 'adopt: %r is not a managed file' % new)
            if new in includes or new in rep.values():
                raise Fail('request', 'adopt: %r would be included twice' % new)
            if not isinstance(how, dict) or how.get('where') not in ('before', 'after') or how.get('anchor') not in includes:
                raise Fail('request', 'adopt: insert %r needs an Include of %s to stand before or after' % (new, main))
            if not re.search(r'/rules/\*\.conf$|REQUEST-\d', how['anchor']):
                raise Fail('request', 'adopt: %r is not a CRS rules Include' % how['anchor'])

    @staticmethod
    def includes(main, text):
        out = {}
        for n, line in enumerate(text.splitlines()):
            m = re.match(r'\s*Include\s+"?([^"\s]+)"?\s*$', line, re.I)
            if m:
                p = m.group(1)
                out[p if os.path.isabs(p) else os.path.join(os.path.dirname(main), p)] = n
        return out

    # --- nginx ------------------------------------------------------------------------------
    def master_pid(self):
        for f in ('/run/nginx.pid', '/var/run/nginx.pid'):
            try:
                with open(f) as fh:
                    return int(fh.read().strip())
            except (OSError, ValueError):
                continue
        return None

    def check_binary(self):
        """A running master whose binary was replaced by a package upgrade loads the new, incompatible
        dynamic module on reload and keeps the old configuration without saying so (LESSONS 3)."""
        pid = self.master_pid()
        if not pid:
            raise Fail('preflight', 'nginx is not running (no pid file)')
        try:
            exe = os.readlink('/proc/%d/exe' % pid)
        except OSError:
            raise Fail('preflight', 'cannot inspect the nginx master process')
        if exe.endswith(' (deleted)'):
            raise Fail('preflight', 'the running nginx binary was replaced by an upgrade; restart nginx first')

    @staticmethod
    def workers():
        """(pid, start ticks, shutting down) of nginx worker processes."""
        out = []
        for d in os.listdir('/proc'):
            if not d.isdigit():
                continue
            try:
                with open('/proc/%s/cmdline' % d, 'rb') as fh:
                    cmd = fh.read().replace(b'\0', b' ').decode('ascii', 'replace')
                if not cmd.startswith('nginx: worker process'):
                    continue
                with open('/proc/%s/stat' % d) as fh:
                    start = int(fh.read().rsplit(')', 1)[1].split()[19])
                out.append((int(d), start, 'shutting down' in cmd))
            except (OSError, ValueError, IndexError):
                continue
        return out

    def reload(self, wait_old):
        before = {pid for pid, _, _ in self.workers()}
        if shutil.which('systemctl') and os.path.isdir('/run/systemd/system'):
            rc, out = run(['systemctl', 'reload', 'nginx'], 60)
        else:
            rc, out = run([self.nginx, '-s', 'reload'], 60)
        if rc != 0:
            raise Fail('reload', 'reload failed: ' + out[-500:])
        # the reload took effect only if new workers appeared
        t0 = time.time()
        while time.time() - t0 < 15:
            new = [p for p, _, down in self.workers() if p not in before and not down]
            if new:
                break
            time.sleep(0.5)
        else:
            raise Fail('reload', 'no new worker processes after reload (configuration not loaded)')
        t0 = time.time()
        while time.time() - t0 < wait_old:
            if not any(down for _, _, down in self.workers()):
                return 'old workers gone after %ds' % (time.time() - t0)
            time.sleep(2)
        return 'old workers still draining after %ds (long-lived connections)' % wait_old

    def test_config(self):
        rc, out = run([self.nginx, '-t'], 120)
        if rc != 0:
            raise Fail('nginx_t', 'nginx -t failed', nginx_t=out[-3000:])
        return out[-1500:]

    # --- health ------------------------------------------------------------------------------
    @staticmethod
    def probe(url):
        u = urllib.parse.urlsplit(url)
        host = u.hostname
        port = u.port or (443 if u.scheme == 'https' else 80)
        try:
            sock = socket.create_connection(('127.0.0.1', port), 15)
            if u.scheme == 'https':
                ctx = ssl.create_default_context()
                ctx.check_hostname = False
                ctx.verify_mode = ssl.CERT_NONE
                sock = ctx.wrap_socket(sock, server_hostname=host)   # SNI carries the site name
            c = http.client.HTTPConnection(host, port, timeout=15)
            c.sock = sock
            c.request('GET', (u.path or '/') + ('?' + u.query if u.query else ''),
                      headers={'Host': u.netloc, 'User-Agent': 'jt-waf-mgr-apply health check'})
            r = c.getresponse()
            r.read(65536)
            c.close()
            return r.status
        except Exception as e:
            return 'error:%s' % type(e).__name__

    def health(self, urls):
        return {u: self.probe(u) for u in urls}

    # --- apply --------------------------------------------------------------------------------
    def snapshot(self, version, extra):
        """The previous contents, kept in memory for the restore (never re-read from disk), plus a copy in
        the root-only state directory for people."""
        os.makedirs(self.backups, mode=0o700, exist_ok=True)
        d = os.path.join(self.backups, 'v%d-before' % version)
        if os.path.lexists(d):
            shutil.rmtree(d) if os.path.isdir(d) and not os.path.islink(d) else os.unlink(d)
        os.mkdir(d, 0o700)
        saved = {}
        for p, f in FILES.items():
            src = os.path.join(self.dir, f)
            saved[src] = _read_plain(src)
            if saved[src] is not None:
                write_atomic(os.path.join(d, f), saved[src], 0o600)
        for src in extra:
            saved[src] = _read_plain(src)
            if saved[src] is None:
                raise Fail('snapshot', 'cannot read %s' % src)
            write_atomic(os.path.join(d, 'main-' + os.path.basename(src)), saved[src], 0o600)
        return saved

    @staticmethod
    def restore(saved):
        for dst, data in saved.items():
            if data is None:
                if os.path.lexists(dst):
                    os.unlink(dst)
            else:
                write_atomic(dst, data)

    def apply(self, req):
        log = []
        t0 = time.time()
        self.check_binary()
        for p, f in FILES.items():
            path = os.path.join(self.dir, f)
            exp = (req.get('expected_disk') or {}).get(p)
            cur = None
            if os.path.exists(path):
                with open(path, 'rb') as fh:
                    cur = sha256(fh.read())
            if req.get('adopt') is None and cur != exp:
                raise Fail('drift', '%s was changed outside jt-waf-mgr; refusing to overwrite' % path)
            if req.get('adopt') is not None and cur is not None:
                raise Fail('drift', '%s already exists; adoption needs a clean managed directory' % path)
        urls = req.get('health_urls') or []
        pre = self.health(urls)
        log.append('health before: %d urls' % len(urls))
        adopt = req.get('adopt')
        saved = self.snapshot(req['version'], [adopt['main_conf']] if adopt else [])
        try:
            os.makedirs(self.dir, mode=0o755, exist_ok=True)
            for p, f in FILES.items():
                write_atomic(os.path.join(self.dir, f), req['files'][p].encode('utf-8'), 0o644)
            if adopt:
                main = adopt['main_conf']
                with open(main, encoding='utf-8') as fh:
                    text = fh.read()
                lines = text.splitlines(keepends=True)
                inc = self.includes(main, text)
                for old, new in (adopt.get('replace') or {}).items():
                    n = inc[old]
                    lines[n] = 'Include %s\n' % new
                # inserts from the bottom up, so the line numbers of the ones above stay right
                at = sorted(((inc[h['anchor']] + (1 if h['where'] == 'after' else 0), new)
                             for new, h in (adopt.get('insert') or {}).items()), reverse=True)
                for pos, new in at:
                    if pos > 0 and not lines[pos - 1].endswith('\n'):
                        lines[pos - 1] += '\n'
                    lines.insert(pos, 'Include %s\n' % new)
                write_atomic(main, ''.join(lines).encode('utf-8'), os.stat(main).st_mode & 0o777)
                log.append('main file now includes the managed files')
            nt = self.test_config()
            log.append('nginx -t ok')
            log.append(self.reload(int(req.get('wait_old_workers') or 120)))
            post = self.health(urls)
            diff = {u: [pre[u], post[u]] for u in urls if pre[u] != post[u]}
            if diff:
                raise Fail('health', 'health check changed for %d url(s)' % len(diff), health=diff)
            return {'result': 'ok', 'step': 'done', 'summary': '; '.join(log), 'nginx_t': nt,
                    'health': {u: [pre[u], post.get(u)] for u in urls}, 'seconds': round(time.time() - t0, 1)}
        except Fail as e:
            self.restore(saved)
            restored = 'restored the previous files'
            try:
                self.test_config()
                self.reload(30)
                restored += ', nginx reloaded'
            except Fail as e2:
                restored += ', BUT reloading them failed: ' + e2.summary
            e.summary += ' -- ' + restored
            raise
        except Exception as e:
            self.restore(saved)
            try:
                self.test_config()
                self.reload(30)
            except Fail:
                pass
            raise Fail('internal', '%s: %s -- restored the previous files' % (type(e).__name__, clean(str(e), 300)))

    def _open_spool(self):
        """The spool is the service user's directory: open it once, refusing a link, and work relative to
        that descriptor so nothing in it can redirect a root write elsewhere."""
        try:
            fd = os.open(self.spool, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        except FileNotFoundError:
            return None
        st = os.fstat(fd)
        if not stat.S_ISDIR(st.st_mode) or st.st_mode & 0o022:
            os.close(fd)
            raise Fail('request', 'the spool directory must not be group or world writable')
        return fd

    # --- OWASP CRS versions (crs -> crs-<version> symlink next to the CRS directory main.conf includes) ---------------
    CRS_KEEP = 3

    def check_crs(self, req):
        """A CRS switch request: install (from the signed tarball the CRS unit staged) or rollback (to a version
        already on the host). Everything is checked again here, as root."""
        if not isinstance(req.get('change_id'), int) or req.get('mode') not in ('install', 'rollback', 'first_install') or \
                not re.fullmatch(r'\d{1,3}\.\d{1,3}\.\d{1,3}', str(req.get('to') or '')):
            raise Fail('request', 'bad CRS switch request')
        crs = req.get('crs_path')
        if req['mode'] == 'first_install':
            main = req.get('main_conf')
            if self.crs_dirs():
                raise Fail('request', 'a CRS is already included')
            if main not in self.main_files() or crs != os.path.join(os.path.dirname(main), 'crs') or os.path.lexists(crs):
                raise Fail('request', 'first installation: crs must be a new directory next to the main ModSecurity file')
            with open(main, encoding='utf-8') as fh:
                if req.get('anchor') is not None and req['anchor'] not in self.includes(main, fh.read()):
                    raise Fail('request', 'the anchor is not an Include of %s' % main)
        elif crs not in self.crs_dirs():
            raise Fail('request', 'crs_path %r is not the CRS directory a main ModSecurity file includes' % crs)
        urls = req.get('health_urls') or []
        if not isinstance(urls, list) or len(urls) > 100 or not all(
                isinstance(u, str) and re.fullmatch(r'https?://[a-z0-9.-]+(?::\d{1,5})?/\S{0,500}', u) for u in urls):
            raise Fail('request', 'bad health check list')
        if req['mode'] in ('install', 'first_install'):
            stage = os.path.realpath(os.path.join(self.cfg['crs']['dir'], 'stage')) + os.sep
            tb = req.get('tarball') or ''
            if not isinstance(tb, str) or os.path.realpath(tb) != tb or not tb.startswith(stage) or \
                    os.path.basename(tb) != 'coreruleset-%s-minimal.tar.gz' % req['to']:
                raise Fail('request', 'the tarball must be the staged coreruleset-%s-minimal.tar.gz' % req['to'])
            if not re.fullmatch(r'[0-9a-f]{64}', str(req.get('tarball_sha256'))) or \
                    not re.fullmatch(r'[0-9a-f]{64}', str(req.get('manifest_sha256'))):
                raise Fail('request', 'bad checksums')
        return req

    def crs_dirs(self):
        """The CRS directories the main ModSecurity files include (<dir>/rules/*.conf)."""
        out = set()
        for main in self.main_files():
            try:
                with open(main, encoding='utf-8') as fh:
                    text = fh.read()
            except OSError:
                continue
            for p in self.includes(main, text):
                if re.search(r'/rules/\*\.conf$', p):
                    out.add(os.path.dirname(os.path.dirname(p)))
        return out

    @staticmethod
    def _read_nofollow(path, limit):
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
        with os.fdopen(fd, 'rb') as fh:
            st = os.fstat(fh.fileno())
            if not stat.S_ISREG(st.st_mode) or st.st_size > limit:
                raise Fail('request', '%s: not a regular file or too large' % os.path.basename(path))
            return fh.read(limit + 1)

    @staticmethod
    def _point(link, name):
        """Point the symlink link at name (a sibling directory) atomically."""
        tmp = os.path.join(os.path.dirname(link), '.%s.new' % os.path.basename(link))
        if os.path.lexists(tmp):
            os.unlink(tmp)
        os.symlink(name, tmp)
        os.replace(tmp, link)

    # --- temporary IP blocks -------------------------------------------------------------------
    def never_blocked(self):
        from .blocks import _nets
        return (list(self.cfg.internal_networks) + list(self.cfg.known_scanners)
                + _nets(self.cfg['server'].get('trusted_proxies')) + _nets(self.cfg['blocks'].get('protected')))

    def check_blocks(self, req):
        from .blocks import validate_entries
        entries = req.get('entries')
        try:
            norm = validate_entries(entries, self.never_blocked())
        except ValueError as e:
            raise Fail('validate', 'blocks: %s' % clean(str(e), 300))
        if norm != entries or hashlib.sha256('\n'.join(entries).encode()).hexdigest() != req.get('sha256'):
            raise Fail('request', 'blocks: the list is not normalised or its checksum does not match')
        return req

    def blocks_write(self, req):
        """Write the deny list (the path comes from the configuration, never from the request), test, reload;
        put the previous file back when nginx -t fails."""
        from .blocks import render
        path = self.cfg['blocks']['file']
        d = os.path.dirname(path)
        if os.path.islink(d) or (os.path.lexists(path) and (os.path.islink(path) or not os.path.isfile(path))):
            raise Fail('blocks', '%s or its directory is a link or not a regular file' % path)
        os.makedirs(d, mode=0o755, exist_ok=True)
        old = None
        if os.path.exists(path):
            old = self._read_nofollow(path, 8 * 1024 * 1024)
        entries = req['entries']
        new = render(entries, path).encode()
        body = lambda b: [l for l in (b or b'').decode('utf-8', 'replace').splitlines() if l and not l.startswith('#')]
        if old is not None and body(old) == body(new):
            return {'result': 'ok', 'count': len(entries), 'sha256': req['sha256'], 'changed': False,
                    'summary': 'unchanged (%d entries)' % len(entries)}
        self.check_binary()
        write_atomic(path, new, 0o644)
        try:
            self.test_config()
        except Fail:
            if old is None:
                os.unlink(path)
            else:
                write_atomic(path, old, 0o644)
            raise
        note = self.reload(0)
        return {'result': 'ok', 'count': len(entries), 'sha256': req['sha256'], 'changed': True,
                'summary': '%d entries written, nginx reloaded (%s)' % (len(entries), note)}

    def crs_switch(self, req):
        from . import crsupdate
        crs, to = req['crs_path'].rstrip('/'), req['to']
        parent = os.path.dirname(crs)
        target = os.path.join(parent, 'crs-%s' % to)
        log = []
        if req['mode'] in ('install', 'first_install'):
            tb = req['tarball']
            data = self._read_nofollow(tb, crsupdate.MAX_DOWNLOAD)
            if hashlib.sha256(data).hexdigest() != req['tarball_sha256']:
                raise Fail('verify', 'the staged tarball changed since it was checked')
            asc = self._read_nofollow(tb + '.asc', 64 * 1024)
            work = tempfile.mkdtemp(prefix='crs-', dir=self.state)
            try:
                t, a = os.path.join(work, os.path.basename(tb)), os.path.join(work, os.path.basename(tb) + '.asc')
                with open(t, 'wb') as fh:
                    fh.write(data)
                with open(a, 'wb') as fh:
                    fh.write(asc)
                if not crsupdate.verify(t, a):
                    raise Fail('verify', 'the signature is not valid or not by the CRS release key')
                log.append('signature ok')
                if os.path.lexists(target):
                    if os.path.islink(target) or not os.path.isdir(target):
                        raise Fail('install', '%s exists and is not a directory' % target)
                    got = self._manifest_sha(target)
                    if got != req['manifest_sha256']:
                        raise Fail('install', '%s exists with other files' % target)
                    log.append('crs-%s already on the host' % to)
                else:
                    tmpd = tempfile.mkdtemp(prefix='.crs-%s.' % to, dir=parent)
                    try:
                        top = crsupdate.safe_extract(t, tmpd, 'coreruleset-%s' % to)
                        if self._manifest_sha(top) != req['manifest_sha256']:
                            raise Fail('verify', 'the unpacked files differ from the ones compared in the sandbox')
                        os.chmod(top, 0o755)
                        os.rename(top, target)
                    finally:
                        shutil.rmtree(tmpd, ignore_errors=True)
                    log.append('installed crs-%s' % to)
            finally:
                shutil.rmtree(work, ignore_errors=True)
        else:
            st = os.lstat(target) if os.path.lexists(target) else None
            if st is None or not stat.S_ISDIR(st.st_mode) or st.st_uid != 0:
                raise Fail('request', 'crs-%s is not a root-owned directory on the host' % to)
        if req['mode'] == 'first_install':
            return self._crs_first(req, crs, target, log)
        if not os.path.islink(crs):
            # first switch: the directory becomes crs-<its version> and crs a link to it (no change in what loads)
            cur = crsupdate.vstr(crsupdate.installed_version(crs))
            if not cur:
                raise Fail('install', 'cannot read the version of %s' % crs)
            keep = os.path.join(parent, 'crs-%s' % cur)
            if os.path.lexists(keep):
                raise Fail('install', '%s already exists' % keep)
            os.rename(crs, keep)
            os.symlink(os.path.basename(keep), crs)
            log.append('%s is now a link to crs-%s' % (crs, cur))
        old = os.readlink(crs)
        if old == os.path.basename(target):
            return {'result': 'ok', 'summary': 'crs-%s is already in use' % to, 'crs': {'from': old, 'to': to}}
        urls = req.get('health_urls') or []
        pre = self.health(urls)
        self._point(crs, os.path.basename(target))
        try:
            self.test_config()
            log.append('nginx -t ok')
            log.append(self.reload(int(req.get('wait_old_workers') or 120)))
            post = self.health(urls)
            diff = {u: [pre[u], post[u]] for u in urls if pre[u] != post[u]}
            if diff:
                raise Fail('health', 'health check changed for %d url(s)' % len(diff), health=diff)
        except Fail as e:
            self._point(crs, old)
            try:
                self.reload(int(req.get('wait_old_workers') or 120))
            except Fail:
                pass
            e.summary += ' -- switched back to %s, nginx reloaded' % old
            raise
        self._prune_crs(parent, keep={os.path.basename(target), old})
        return {'result': 'ok', 'summary': '; '.join(log + ['crs -> crs-%s' % to]), 'crs': {'from': old, 'to': to}}

    def _crs_first(self, req, crs, target, log):
        """No CRS yet: crs -> crs-<version>, crs-setup.conf from its example (unless there is one), and the two
        Includes right after the anchor in the main file. Any failure puts everything back as it was."""
        main, anchor = req['main_conf'], req.get('anchor')
        parent = os.path.dirname(crs)
        setup = os.path.join(parent, 'crs-setup.conf')
        with open(main, encoding='utf-8') as fh:
            original = fh.read()
        mode = os.stat(main).st_mode & 0o777
        lines = original.splitlines(keepends=True)
        new = ['Include %s\n' % setup, 'Include %s\n' % os.path.join(crs, 'rules', '*.conf')]
        inc = self.includes(main, original)
        pos = inc[anchor] + 1 if anchor is not None else len(lines)
        if pos > 0 and lines and not lines[pos - 1].endswith('\n'):
            lines[pos - 1] += '\n'
        lines[pos:pos] = new
        urls = req.get('health_urls') or []
        pre = self.health(urls)
        made_setup = not os.path.exists(setup)
        try:
            os.symlink(os.path.basename(target), crs)
            if made_setup:
                shutil.copyfile(os.path.join(target, 'crs-setup.conf.example'), setup)
                os.chmod(setup, 0o644)
            write_atomic(main, ''.join(lines).encode('utf-8'), mode)
            self.test_config()
            log.append('nginx -t ok')
            log.append(self.reload(int(req.get('wait_old_workers') or 120)))
            post = self.health(urls)
            diff = {u: [pre[u], post[u]] for u in urls if pre[u] != post[u]}
            if diff:
                raise Fail('health', 'health check changed for %d url(s)' % len(diff), health=diff)
        except Exception as e:      # noqa: BLE001 -- whatever went wrong, nothing of it stays
            if not isinstance(e, Fail):
                e = Fail('install', '%s: %s' % (type(e).__name__, clean(str(e), 300)))
            write_atomic(main, original.encode('utf-8'), mode)
            for p in [crs] + ([setup] if made_setup else []):
                try:
                    os.unlink(p)
                except OSError:
                    pass
            shutil.rmtree(target, ignore_errors=True)
            try:
                self.reload(int(req.get('wait_old_workers') or 120))
            except Fail:
                pass
            e.summary += ' -- the CRS was taken out again, nginx reloaded'
            raise e
        log.append('crs -> crs-%s included in %s' % (req['to'], main))
        return {'result': 'ok', 'summary': '; '.join(log), 'crs': {'from': None, 'to': req['to']}}

    @staticmethod
    def _manifest_sha(path):
        from . import crsupdate
        return hashlib.sha256(json.dumps(crsupdate.manifest(path), sort_keys=True).encode()).hexdigest()

    def _prune_crs(self, parent, keep):
        from . import crsupdate
        found = sorted((n for n in os.listdir(parent) if re.fullmatch(r'crs-\d+\.\d+\.\d+', n)
                        and os.path.isdir(os.path.join(parent, n)) and not os.path.islink(os.path.join(parent, n))),
                       key=lambda n: crsupdate.vtuple(n[4:]))
        for n in found[:-self.CRS_KEEP] if len(found) > self.CRS_KEEP else []:
            if n not in keep:
                shutil.rmtree(os.path.join(parent, n), ignore_errors=True)

    def process(self):
        os.makedirs(self.state, mode=0o700, exist_ok=True)
        os.chmod(self.state, 0o700)
        with open(os.path.join(self.state, 'apply.lock'), 'w') as lockf:
            fcntl.flock(lockf, fcntl.LOCK_EX)
            self._spool_fd = self._open_spool()
            if self._spool_fd is None:
                return
            try:
                self._process()
            finally:
                os.close(self._spool_fd)
                self._spool_fd = None

    def _process(self):
        names = sorted(n for n in os.listdir(self._spool_fd) if n.endswith('.req') and re.fullmatch(r'[\w.-]+', n))
        refused = self.program_refusal() if names else None
        for n in names:
            path = os.path.join(self.spool, n)
            base = n[:-4]
            res = {'request_id': base}
            try:
                if refused:
                    raise Fail('integrity', refused)
                req = self.load_request(path)
                if req.get('action') == 'crs_switch':
                    res.update(action='crs_switch', change_id=req['change_id'])
                    res.update(self.crs_switch(req))
                elif req.get('action') == 'blocks':
                    res.update(action='blocks')
                    res.update(self.blocks_write(req))
                else:
                    res.update(version=req['version'], change_id=req['change_id'])
                    res.update(self.apply(req))
            except Fail as e:
                res.update(result='failed', step=e.step, summary=e.summary, **e.extra)
            except Exception as e:
                res.update(result='failed', step='request', summary='%s: %s' % (type(e).__name__, clean(str(e), 300)))
            if base.startswith('blocks-'):
                res.update(action='blocks')
            mc = re.match(r'crs-c(\d+)$', base)
            if mc:
                res.update(action='crs_switch', change_id=int(mc.group(1)))
            m = re.match(r'v(\d+)-c(\d+)$', base)
            if m and 'version' not in res:
                res.update(version=int(m.group(1)), change_id=int(m.group(2)))
            write_atomic(base + '.result', json.dumps(res, ensure_ascii=True).encode(), 0o644, dir_fd=self._spool_fd)
            os.unlink(n, dir_fd=self._spool_fd)   # the path unit must not fire again for it
            print('%s: %s %s' % (base, res.get('result'), res.get('summary', '')), flush=True)
        self.prune()

    program_check = None   # set by main(): checks the installed program against the signed manifest

    def program_refusal(self):
        """A reason to refuse every request when the installed program does not match its signed
        manifest (a root program must not run modified code), else None."""
        if self.program_check is None:
            return None
        res = self.program_check()
        if res['status'] == 'ok':
            return None
        if res['status'] == 'not_installed' and res['dir'] != INSTALL_DIR:
            return None   # running from a source tree (development)
        return 'program integrity check failed (%s): changed %s, missing %s, extra %s' % (
            res.get('reason') or res['status'], res.get('changed', [])[:5], res.get('missing', [])[:5],
            res.get('extra', [])[:5])

    def prune(self):
        keep = int(self.cfg['managed']['snapshots_kept'])
        try:
            olds = sorted((d for d in os.listdir(self.backups) if re.match(r'v\d+-before$', d)),
                          key=lambda d: int(d[1:].split('-')[0]))
        except OSError:
            return
        for d in olds[:-keep] if keep > 0 else []:
            shutil.rmtree(os.path.join(self.backups, d), ignore_errors=True)


