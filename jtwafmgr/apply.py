"""jt-waf-mgr-apply: the only component that runs as root (SPEC 4, 6.4).

Started by systemd when a request appears in the spool directory. It trusts nothing in the
request beyond "which version to write": paths come from its own configuration, every file is
checked again (allowed directives only, nothing from the forbidden list), the checksum must match,
and the files on disk must be the ones the request was prepared against (no manual edits).

Then: lock -> snapshot -> health check before -> write -> nginx -t -> reload -> verify the reload
took effect -> wait for old workers -> health check after; any failure restores the snapshot.

  python3 -m jtwafmgr.apply [--config /etc/jt-waf-mgr/config.toml] [--once]
"""
import argparse
import fcntl
import hashlib
import http.client
import json
import os
import re
import shutil
import stat
import socket
import ssl
import subprocess
import sys
import time
import urllib.parse

from . import config as config_mod
from .managed import FILES
from .rulegen import SpecError, check_raw_text

MAX_REQUEST = 4 * 1024 * 1024


class Fail(Exception):
    def __init__(self, step, summary, **extra):
        super().__init__(summary)
        self.step, self.summary, self.extra = step, summary, extra


def sha256(b):
    return hashlib.sha256(b if isinstance(b, bytes) else b.encode('utf-8')).hexdigest()


def clean(s, n=4000):
    s = s.decode('utf-8', 'replace') if isinstance(s, bytes) else s
    return re.sub(r'[^\x09\x0a\x20-\x7e]', '?', s)[-n:]


def run(cmd, timeout=60):
    p = subprocess.run(cmd, capture_output=True, timeout=timeout)
    return p.returncode, clean(p.stdout + p.stderr)


class Applier:
    def __init__(self, cfg):
        self.cfg = cfg
        self.dir = cfg['managed']['dir']
        self.spool = cfg['managed']['spool']
        self.nginx = cfg['paths']['nginx_bin']
        self.state = cfg['managed']['apply_state']
        self.backups = os.path.join(self.state, 'snapshots')
        self._spool_fd = None

    # --- request validation ----------------------------------------------------------------
    def load_request(self, path):
        # the spool belongs to the service user: open without following links and check what was opened
        name = os.path.basename(path)
        dfd = self._spool_fd
        try:
            fd = os.open(name if dfd is not None else path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
                         dir_fd=dfd)
        except OSError as e:
            raise Fail('request', 'cannot open the request: %s' % e.strerror)
        with os.fdopen(fd, 'rb') as fh:
            st = os.fstat(fh.fileno())
            if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_REQUEST or st.st_nlink != 1:
                raise Fail('request', 'not a regular file or too large')
            req = json.loads(fh.read(MAX_REQUEST + 1).decode('utf-8'))
        if not isinstance(req, dict) or req.get('action') != 'apply':
            raise Fail('request', 'unknown action')
        if not isinstance(req.get('version'), int) or not isinstance(req.get('change_id'), int):
            raise Fail('request', 'bad version or change id')
        files = req.get('files')
        if not isinstance(files, dict) or set(files) != set(FILES):
            raise Fail('request', 'files must be exactly: %s' % ', '.join(FILES))
        for p, text in files.items():
            if not isinstance(text, str) or sha256(text) != (req.get('sha256') or {}).get(p):
                raise Fail('request', 'checksum mismatch for %s' % p)
            if not text.startswith('# Generated by jt-waf-mgr'):
                raise Fail('request', '%s: missing jt-waf-mgr header' % p)
            body = text.split('\n\n', 1)[1] if '\n\n' in text else ''
            if len(text) > 4 * 1024 * 1024:
                raise Fail('request', '%s: file too large' % p)
            if body.strip():
                # the same per-rule checks as the workflow, done again here as root (never trust the request);
                # the limits are per rule, so the file is checked rule by rule
                from .managed import split_items
                ids = []
                for it in split_items(body):
                    if not it['text']:
                        continue
                    try:
                        ids += check_raw_text(it['text'], cfg=self.cfg)
                    except SpecError as e:
                        raise Fail('validate', '%s: rule %s: %s %s' % (p, it.get('rule_id'), e.code, e.details))
                lo, hi = self.cfg['waf']['local_range']
                bad = [i for i in ids if not lo <= i <= hi]
                if bad:
                    raise Fail('validate', '%s: rule ids outside the local range: %s' % (p, bad[:5]))
        urls = req.get('health_urls') or []
        if not isinstance(urls, list) or len(urls) > 100 or not all(
                isinstance(u, str) and re.fullmatch(r'https?://[a-z0-9.-]+(?::\d{1,5})?/\S{0,500}', u) for u in urls):
            raise Fail('request', 'bad health check list')
        adopt = req.get('adopt')
        if adopt is not None:
            self.check_adopt(adopt)
        return req

    def main_files(self):
        from .modsecconf import ModsecConfig
        from .nginxconf import NginxConfig
        n = NginxConfig(self.cfg['paths']['nginx_conf'])
        return ModsecConfig(n, self.cfg).main_files

    def check_adopt(self, adopt):
        main = adopt.get('main_conf')
        if main not in self.main_files():
            raise Fail('request', 'adopt: %r is not the main ModSecurity file' % main)
        rep = adopt.get('replace') or {}
        if not isinstance(rep, dict) or not rep:
            raise Fail('request', 'adopt: nothing to replace')
        allowed = {os.path.join(self.dir, f) for f in FILES.values()}
        with open(main, encoding='utf-8') as fh:
            text = fh.read()
        includes = self.includes(main, text)
        for old, new in rep.items():
            if new not in allowed:
                raise Fail('request', 'adopt: %r is not a managed file' % new)
            if old not in includes:
                raise Fail('request', 'adopt: %r is not included by %s' % (old, main))

    @staticmethod
    def includes(main, text):
        out = {}
        for n, line in enumerate(text.splitlines()):
            m = re.match(r'\s*Include\s+"?([^"\s]+)"?\s*$', line, re.I)
            if m:
                p = m.group(1)
                out[p if os.path.isabs(p) else os.path.join(os.path.dirname(main), p)] = n
        return out

    # --- nginx ------------------------------------------------------------------------------
    def master_pid(self):
        for f in ('/run/nginx.pid', '/var/run/nginx.pid'):
            try:
                with open(f) as fh:
                    return int(fh.read().strip())
            except (OSError, ValueError):
                continue
        return None

    def check_binary(self):
        """A running master whose binary was replaced by a package upgrade loads the new, incompatible
        dynamic module on reload and keeps the old configuration without saying so (LESSONS 3)."""
        pid = self.master_pid()
        if not pid:
            raise Fail('preflight', 'nginx is not running (no pid file)')
        try:
            exe = os.readlink('/proc/%d/exe' % pid)
        except OSError:
            raise Fail('preflight', 'cannot inspect the nginx master process')
        if exe.endswith(' (deleted)'):
            raise Fail('preflight', 'the running nginx binary was replaced by an upgrade; restart nginx first')

    @staticmethod
    def workers():
        """(pid, start ticks, shutting down) of nginx worker processes."""
        out = []
        for d in os.listdir('/proc'):
            if not d.isdigit():
                continue
            try:
                with open('/proc/%s/cmdline' % d, 'rb') as fh:
                    cmd = fh.read().replace(b'\0', b' ').decode('ascii', 'replace')
                if not cmd.startswith('nginx: worker process'):
                    continue
                with open('/proc/%s/stat' % d) as fh:
                    start = int(fh.read().rsplit(')', 1)[1].split()[19])
                out.append((int(d), start, 'shutting down' in cmd))
            except (OSError, ValueError, IndexError):
                continue
        return out

    def reload(self, wait_old):
        before = {pid for pid, _, _ in self.workers()}
        if shutil.which('systemctl') and os.path.isdir('/run/systemd/system'):
            rc, out = run(['systemctl', 'reload', 'nginx'], 60)
        else:
            rc, out = run([self.nginx, '-s', 'reload'], 60)
        if rc != 0:
            raise Fail('reload', 'reload failed: ' + out[-500:])
        # the reload took effect only if new workers appeared
        t0 = time.time()
        while time.time() - t0 < 15:
            new = [p for p, _, down in self.workers() if p not in before and not down]
            if new:
                break
            time.sleep(0.5)
        else:
            raise Fail('reload', 'no new worker processes after reload (configuration not loaded)')
        t0 = time.time()
        while time.time() - t0 < wait_old:
            if not any(down for _, _, down in self.workers()):
                return 'old workers gone after %ds' % (time.time() - t0)
            time.sleep(2)
        return 'old workers still draining after %ds (long-lived connections)' % wait_old

    def test_config(self):
        rc, out = run([self.nginx, '-t'], 120)
        if rc != 0:
            raise Fail('nginx_t', 'nginx -t failed', nginx_t=out[-3000:])
        return out[-1500:]

    # --- health ------------------------------------------------------------------------------
    @staticmethod
    def probe(url):
        u = urllib.parse.urlsplit(url)
        host = u.hostname
        port = u.port or (443 if u.scheme == 'https' else 80)
        try:
            sock = socket.create_connection(('127.0.0.1', port), 15)
            if u.scheme == 'https':
                ctx = ssl.create_default_context()
                ctx.check_hostname = False
                ctx.verify_mode = ssl.CERT_NONE
                sock = ctx.wrap_socket(sock, server_hostname=host)   # SNI carries the site name
            c = http.client.HTTPConnection(host, port, timeout=15)
            c.sock = sock
            c.request('GET', (u.path or '/') + ('?' + u.query if u.query else ''),
                      headers={'Host': u.netloc, 'User-Agent': 'jt-waf-mgr-apply health check'})
            r = c.getresponse()
            r.read(65536)
            c.close()
            return r.status
        except Exception as e:
            return 'error:%s' % type(e).__name__

    def health(self, urls):
        return {u: self.probe(u) for u in urls}

    # --- apply --------------------------------------------------------------------------------
    def snapshot(self, version, extra):
        """The previous contents, kept in memory for the restore (never re-read from disk), plus a copy in
        the root-only state directory for people."""
        os.makedirs(self.backups, mode=0o700, exist_ok=True)
        d = os.path.join(self.backups, 'v%d-before' % version)
        if os.path.lexists(d):
            shutil.rmtree(d) if os.path.isdir(d) and not os.path.islink(d) else os.unlink(d)
        os.mkdir(d, 0o700)
        saved = {}
        for p, f in FILES.items():
            src = os.path.join(self.dir, f)
            saved[src] = _read_plain(src)
            if saved[src] is not None:
                write_atomic(os.path.join(d, f), saved[src], 0o600)
        for src in extra:
            saved[src] = _read_plain(src)
            if saved[src] is None:
                raise Fail('snapshot', 'cannot read %s' % src)
            write_atomic(os.path.join(d, 'main-' + os.path.basename(src)), saved[src], 0o600)
        return saved

    @staticmethod
    def restore(saved):
        for dst, data in saved.items():
            if data is None:
                if os.path.lexists(dst):
                    os.unlink(dst)
            else:
                write_atomic(dst, data)

    def apply(self, req):
        log = []
        t0 = time.time()
        self.check_binary()
        for p, f in FILES.items():
            path = os.path.join(self.dir, f)
            exp = (req.get('expected_disk') or {}).get(p)
            cur = None
            if os.path.exists(path):
                with open(path, 'rb') as fh:
                    cur = sha256(fh.read())
            if req.get('adopt') is None and cur != exp:
                raise Fail('drift', '%s was changed outside jt-waf-mgr; refusing to overwrite' % path)
            if req.get('adopt') is not None and cur is not None:
                raise Fail('drift', '%s already exists; adoption needs a clean managed directory' % path)
        urls = req.get('health_urls') or []
        pre = self.health(urls)
        log.append('health before: %d urls' % len(urls))
        adopt = req.get('adopt')
        saved = self.snapshot(req['version'], [adopt['main_conf']] if adopt else [])
        try:
            os.makedirs(self.dir, mode=0o755, exist_ok=True)
            for p, f in FILES.items():
                write_atomic(os.path.join(self.dir, f), req['files'][p].encode('utf-8'), 0o644)
            if adopt:
                main = adopt['main_conf']
                with open(main, encoding='utf-8') as fh:
                    text = fh.read()
                lines = text.splitlines(keepends=True)
                inc = self.includes(main, text)
                for old, new in adopt['replace'].items():
                    n = inc[old]
                    lines[n] = 'Include %s\n' % new
                write_atomic(main, ''.join(lines).encode('utf-8'), os.stat(main).st_mode & 0o777)
                log.append('main file now includes the managed files')
            nt = self.test_config()
            log.append('nginx -t ok')
            log.append(self.reload(int(req.get('wait_old_workers') or 120)))
            post = self.health(urls)
            diff = {u: [pre[u], post[u]] for u in urls if pre[u] != post[u]}
            if diff:
                raise Fail('health', 'health check changed for %d url(s)' % len(diff), health=diff)
            return {'result': 'ok', 'step': 'done', 'summary': '; '.join(log), 'nginx_t': nt,
                    'health': {u: [pre[u], post.get(u)] for u in urls}, 'seconds': round(time.time() - t0, 1)}
        except Fail as e:
            self.restore(saved)
            restored = 'restored the previous files'
            try:
                self.test_config()
                self.reload(30)
                restored += ', nginx reloaded'
            except Fail as e2:
                restored += ', BUT reloading them failed: ' + e2.summary
            e.summary += ' -- ' + restored
            raise
        except Exception as e:
            self.restore(saved)
            try:
                self.test_config()
                self.reload(30)
            except Fail:
                pass
            raise Fail('internal', '%s: %s -- restored the previous files' % (type(e).__name__, clean(str(e), 300)))

    def _open_spool(self):
        """The spool is the service user's directory: open it once, refusing a link, and work relative to
        that descriptor so nothing in it can redirect a root write elsewhere."""
        try:
            fd = os.open(self.spool, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        except FileNotFoundError:
            return None
        st = os.fstat(fd)
        if not stat.S_ISDIR(st.st_mode) or st.st_mode & 0o022:
            os.close(fd)
            raise Fail('request', 'the spool directory must not be group or world writable')
        return fd

    def process(self):
        os.makedirs(self.state, mode=0o700, exist_ok=True)
        os.chmod(self.state, 0o700)
        with open(os.path.join(self.state, 'apply.lock'), 'w') as lockf:
            fcntl.flock(lockf, fcntl.LOCK_EX)
            self._spool_fd = self._open_spool()
            if self._spool_fd is None:
                return
            try:
                self._process()
            finally:
                os.close(self._spool_fd)
                self._spool_fd = None

    def _process(self):
        names = sorted(n for n in os.listdir(self._spool_fd) if n.endswith('.req') and re.fullmatch(r'[\w.-]+', n))
        refused = self.program_refusal() if names else None
        for n in names:
            path = os.path.join(self.spool, n)
            base = n[:-4]
            res = {'request_id': base}
            try:
                if refused:
                    raise Fail('integrity', refused)
                req = self.load_request(path)
                res.update(version=req['version'], change_id=req['change_id'])
                res.update(self.apply(req))
            except Fail as e:
                res.update(result='failed', step=e.step, summary=e.summary, **e.extra)
            except Exception as e:
                res.update(result='failed', step='request', summary='%s: %s' % (type(e).__name__, clean(str(e), 300)))
            m = re.match(r'v(\d+)-c(\d+)$', base)
            if m and 'version' not in res:
                res.update(version=int(m.group(1)), change_id=int(m.group(2)))
            write_atomic(base + '.result', json.dumps(res, ensure_ascii=True).encode(), 0o644, dir_fd=self._spool_fd)
            os.unlink(n, dir_fd=self._spool_fd)   # the path unit must not fire again for it
            print('%s: %s %s' % (base, res.get('result'), res.get('summary', '')), flush=True)
        self.prune()

    program_check = None   # set by main(): checks the installed program against the signed manifest

    def program_refusal(self):
        """A reason to refuse every request when the installed program does not match its signed
        manifest (a root program must not run modified code), else None."""
        if self.program_check is None:
            return None
        res = self.program_check()
        if res['status'] == 'ok':
            return None
        if res['status'] == 'not_installed' and res['dir'] != INSTALL_DIR:
            return None   # running from a source tree (development)
        return 'program integrity check failed (%s): changed %s, missing %s, extra %s' % (
            res.get('reason') or res['status'], res.get('changed', [])[:5], res.get('missing', [])[:5],
            res.get('extra', [])[:5])

    def prune(self):
        keep = int(self.cfg['managed']['snapshots_kept'])
        try:
            olds = sorted((d for d in os.listdir(self.backups) if re.match(r'v\d+-before$', d)),
                          key=lambda d: int(d[1:].split('-')[0]))
        except OSError:
            return
        for d in olds[:-keep] if keep > 0 else []:
            shutil.rmtree(os.path.join(self.backups, d), ignore_errors=True)


from .integrity import INSTALL_DIR  # noqa: E402


def _read_plain(path):
    """Contents of a regular file (not following a final symlink), None when it does not exist."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except FileNotFoundError:
        return None
    with os.fdopen(fd, 'rb') as fh:
        if not stat.S_ISREG(os.fstat(fh.fileno()).st_mode):
            raise Fail('snapshot', '%s is not a regular file' % path)
        return fh.read()


def write_atomic(path, data, mode=None, dir_fd=None):
    """Write a temporary file next to the target (exclusive create, never through a link) and rename it
    over the target. With dir_fd, path is a name inside that directory."""
    if dir_fd is None:
        d, name = os.path.split(path)
        dfd = os.open(d or '.', os.O_RDONLY | os.O_DIRECTORY)
    else:
        dfd, name = dir_fd, path
    tmp = '.%s.jtwaf-tmp' % name
    try:
        try:
            os.unlink(tmp, dir_fd=dfd)
        except FileNotFoundError:
            pass
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=dfd)
        with os.fdopen(fd, 'wb') as fh:
            fh.write(data)
            fh.flush()
            os.fchmod(fh.fileno(), mode if mode is not None else 0o644)
            os.fsync(fh.fileno())
        os.replace(tmp, name, src_dir_fd=dfd, dst_dir_fd=dfd)
    finally:
        if dir_fd is None:
            os.close(dfd)


def main(argv=None):
    ap = argparse.ArgumentParser(prog='jt-waf-mgr-apply')
    ap.add_argument('--config', default=config_mod.default_path())
    a = ap.parse_args(argv)
    if os.geteuid() != 0:
        print('jt-waf-mgr-apply must run as root', file=sys.stderr)
        return 1
    cfg = config_mod.load(a.config)
    from . import integrity
    ap = Applier(cfg)
    ap.program_check = lambda: integrity.verify_program(key_path=cfg['integrity']['release_key'])
    ap.process()
    return 0


if __name__ == '__main__':
    sys.exit(main())
