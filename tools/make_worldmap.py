#!/usr/bin/env python3
"""Turn an equirectangular land outline SVG (viewBox 0 0 360 180, one <path> of country polygons) into the front-end
module frontend/src/components/charts/worldLand.js (one path string, coordinates rounded to 0.1 degree).

  tools/make_worldmap.py SOURCE.svg

The outline comes from jt-glogarch's report assets (same author, AGPL-3.0). Its two digitising artefacts (thin
full-width strips at about 71 N and 16 S) are dropped, the same way jt-glogarch does it.
"""
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'frontend', 'src', 'components', 'charts',
                   'worldLand.js')


def pieces(d):
    out = []
    for sp in [s for s in re.split(r'(?=[Mm])', d) if s.strip()]:
        n = [float(x) for x in re.findall(r'-?\d+\.?\d*', sp)]
        pts = list(zip(n[0::2], n[1::2]))
        if not pts:
            continue
        xr = max(p[0] for p in pts) - min(p[0] for p in pts)
        yr = max(p[1] for p in pts) - min(p[1] for p in pts)
        if xr > 300 and yr < 3:
            continue                                  # a whole thin strip
        drop = [False] * len(pts)
        i = 0
        while i < len(pts):                           # long horizontal runs that are not the Antarctic edge
            j = i + 1
            while j < len(pts) and abs(pts[j][1] - pts[i][1]) < 1.5:
                j += 1
            seg = pts[i:j]
            if j - i >= 3 and max(p[0] for p in seg) - min(p[0] for p in seg) > 120 and pts[i][1] < 150:
                for k in range(i, j):
                    drop[k] = True
            i = j if j > i + 1 else i + 1
        run = []
        for k, p in enumerate(pts + [None]):
            if p is None or drop[k]:
                if len(run) >= 3:
                    out.append(run)
                run = []
            else:
                run.append(p)
    return out


def fmt(v):
    s = ('%.1f' % v).rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'


def main(src):
    svg = open(src, encoding='utf-8').read()
    m = re.search(r'<path[^>]*\sd="([^"]+)"', svg)
    if not m or 'viewBox="0 0 360 180"' not in svg:
        sys.exit('expected one land <path> in a 360 x 180 equirectangular SVG')
    parts = []
    for run in pieces(m.group(1)):
        pts, last = [], None
        for x, y in run:
            p = (fmt(x), fmt(y))
            if p != last:
                pts.append(p)
                last = p
        if len(pts) >= 3:
            parts.append('M' + 'L'.join('%s,%s' % p for p in pts) + 'Z')
    d = ''.join(parts)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Land outline, equirectangular, viewBox 0 0 360 180 (x = longitude + 180, y = 90 - latitude).\n'
                '// Generated by tools/make_worldmap.py from jt-glogarch\'s report asset (same author, AGPL-3.0). Do not edit.\n')
        f.write('export default %r\n' % d)
    print('%s: %d polygons, %d bytes' % (OUT, len(parts), len(d)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
